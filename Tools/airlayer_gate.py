#!/usr/bin/env python3
"""Version gate helper for RTL8814AirLayer.

  gen [--check]   write Source/AirLayer/KnownBuilds.inc from the generated
                  IO80211 header (class sizes and superclasses) and
                  Tools/airlayer_builds.txt (validated builds)
  status          read the gate result the loaded kext published in the
                  I/O Registry and say what to do next
  trust-arg       print the boot-arg that lets the layer start on this build
  learn [--yes]   add this build to the validated list, after `status` shows
                  that the structure matches, and regenerate the table
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "Source/IO80211/IO80211_25_6_0.h")
BUILDS = os.path.join(ROOT, "Tools/airlayer_builds.txt")
OUT = os.path.join(ROOT, "Source/AirLayer/KnownBuilds.inc")

# Order matters: it is the order of GateReference.cls[] in the kext.
CLASSES = ["IOSkywalkInterface", "IOSkywalkNetworkInterface", "IOSkywalkEthernetInterface",
           "IO80211SkywalkInterface", "IO80211InfraInterface", "IO80211InfraProtocol",
           "IO80211Controller"]


def sh(*cmd):
    return subprocess.run(cmd, capture_output=True, text=True).stdout.strip()


def read_header():
    text = open(HEADER).read()
    sup = dict(re.findall(r"^class (\w+) : public (\w+) \{", text, re.M))
    size = {n: int(v, 16) for n, v in re.findall(r"static_assert\(sizeof\((\w+)\) == (0x[0-9a-fA-F]+)", text)}
    missing = [c for c in CLASSES if c not in sup or c not in size]
    if missing:
        sys.exit("header %s lacks class/size for: %s" % (HEADER, ", ".join(missing)))
    return sup, size


def read_builds():
    darwin, builds = None, []
    for line in open(BUILDS):
        line = line.split("#", 1)[0].strip() if line.lstrip().startswith("#") else line.rstrip("\n")
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "darwin" and len(parts) >= 2:
            darwin = int(parts[1])
        elif parts[0] == "build" and len(parts) >= 3:
            builds.append((parts[1], parts[2], " ".join(parts[3:])))
    if darwin is None:
        sys.exit("%s has no 'darwin <major>' line" % BUILDS)
    return darwin, builds


def render():
    sup, size = read_header()
    darwin, builds = read_builds()
    o = ["/* Generated by Tools/airlayer_gate.py gen from Source/IO80211/IO80211_25_6_0.h",
         " * and Tools/airlayer_builds.txt. Do not edit by hand. */",
         "static const GateReference kGateRef = {", "\t%d," % darwin, "\t{"]
    for c in CLASSES:
        o.append('\t\t{ "%s", "%s", 0x%x },' % (c, sup[c], size[c]))
    o += ["\t}", "};", ""]
    ids = ", ".join('"%s"' % b[0] for b in builds) if builds else '""'
    o.append("static const char *const kGateValidated[] = { %s };" % ids)
    o.append("static const size_t kGateValidatedCount = %d;" % len(builds))
    return "\n".join(o) + "\n"


def cmd_gen(args):
    text = render()
    if "--check" in args:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("KnownBuilds.inc is %s" % ("up to date" if same else "OUT OF DATE (run: Tools/airlayer_gate.py gen)"))
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print("wrote %s" % os.path.relpath(OUT, ROOT))


def registry():
    out = sh("ioreg", "-r", "-c", "RTL8814Native", "-d", "1", "-w0")
    gate = re.search(r'"RTLAirGate"\s*=\s*"([^"]*)"', out)
    build = re.search(r'"RTLAirGateBuild"\s*=\s*"([^"]*)"', out)
    return (gate.group(1) if gate else None), (build.group(1) if build else None)


def cmd_status(_):
    gate, build = registry()
    cur = sh("sw_vers", "-buildVersion")
    ver = sh("sw_vers", "-productVersion")
    print("macOS %s (%s)" % (ver, cur))
    if not gate:
        print("The kext published no gate result: it is not loaded, not armed (boot-arg rtlair=1|2),\n"
              "or it is a build older than 0.32. Check the EFI and the boot-args.")
        return 2
    print("gate: %s" % gate)
    verdict = gate.split(":", 1)[0]
    if verdict.startswith("open"):
        print("-> the layer was allowed to start on this build.")
        return 0
    if verdict == "closed-unknown-build":
        print("-> structure matches but this build was never validated. To try it:\n"
              "   1. add `rtlairtrust=%s` to boot-args and reboot\n"
              "   2. test scan, join and data\n"
              "   3. `Tools/airlayer_gate.py learn --yes`, rebuild, redeploy" % (build or cur))
        return 1
    print("-> a class changed: this macOS needs a new header (Tools/re/gen_io80211.py) and a new build.\n"
          "   The layer stayed inert; en2 keeps working.")
    return 1


def cmd_trust_arg(_):
    print("rtlairtrust=%s" % sh("sw_vers", "-buildVersion"))


def cmd_learn(args):
    gate, build = registry()
    cur = build or sh("sw_vers", "-buildVersion")
    if not gate or not gate.startswith(("closed-unknown-build", "open-trusted")):
        sys.exit("learn needs the gate to report closed-unknown-build or open-trusted\n"
                 "(structure verified by the kext on this build). Current gate: %s" % (gate or "none"))
    darwin, builds = read_builds()
    if cur in [b[0] for b in builds]:
        sys.exit("build %s is already validated" % cur)
    line = "build %s %s validated %s\n" % (cur, sh("sw_vers", "-productVersion"), sh("date", "+%Y-%m-%d"))
    if "--yes" not in args:
        print("would append to %s:\n  %s\nrun again with --yes" % (os.path.relpath(BUILDS, ROOT), line.strip()))
        return
    with open(BUILDS, "a") as f:
        f.write(line)
    cmd_gen([])
    print("now: ./build_airlayer.sh and redeploy")


if __name__ == "__main__":
    cmds = {"gen": cmd_gen, "status": cmd_status, "trust-arg": cmd_trust_arg, "learn": cmd_learn}
    if len(sys.argv) < 2 or sys.argv[1] not in cmds:
        sys.exit(__doc__)
    r = cmds[sys.argv[1]](sys.argv[2:])
    sys.exit(r if isinstance(r, int) else 0)
