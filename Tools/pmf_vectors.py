#!/usr/bin/env python3
"""Generate Tools/pmf_vectors.h: independent CCMP and BIP vectors for PMF.c
(python cryptography AES-CCM / CMAC, built from the 802.11 construction)."""
import struct
from cryptography.hazmat.primitives.ciphers.aead import AESCCM
from cryptography.hazmat.primitives.cmac import CMAC
from cryptography.hazmat.primitives.ciphers import algorithms

def c(name, b):
    return "static const unsigned char %s[] = {%s};\n" % (name, ",".join("0x%02x" % x for x in b))

tk = bytes(range(16, 32))
a1 = bytes.fromhex("7cc2c603ea84"); a2 = bytes.fromhex("468162244020"); a3 = a2
fc_deauth = 0x00c0
out = "/* generated by pmf_vectors.py */\n" + c("pmf_tk", tk)

def ccmp_frame(body, pn, retry=False, sc=0x1230):
    fc = fc_deauth | 0x4000 | (0x0800 if retry else 0)
    hdr = struct.pack("<H", fc) + b"\x00\x00" + a1 + a2 + a3 + struct.pack("<H", sc)
    nonce = bytes([0x10]) + a2 + pn.to_bytes(6, "big")
    fcm = (fc & ~0x3800)
    aad = struct.pack("<H", fcm) + a1 + a2 + a3 + struct.pack("<H", sc & 0x000f)
    ct = AESCCM(tk, tag_length=8).encrypt(nonce, body, aad)
    p = pn.to_bytes(6, "little")
    ccmp = bytes([p[0], p[1], 0, 0x20, p[2], p[3], p[4], p[5]])
    return hdr + ccmp + ct

body = struct.pack("<H", 3)
out += c("pmf_deauth_plain", bytes(24) and (struct.pack("<H", fc_deauth) + b"\x00\x00" + a1 + a2 + a3 + struct.pack("<H", 0x1230) + body))
out += c("pmf_deauth_enc", ccmp_frame(body, 0x0102030405a6))
out += c("pmf_deauth_enc_retry", ccmp_frame(body, 0x000000000099, retry=True))
body2 = bytes(range(7, 7 + 37))
out += c("pmf_action_plain", struct.pack("<H", 0x00d0) + b"\x00\x00" + a1 + a2 + a3 + struct.pack("<H", 0x1230) + body2)
fc = 0x00d0 | 0x4000
hdr = struct.pack("<H", fc) + b"\x00\x00" + a1 + a2 + a3 + struct.pack("<H", 0x1230)
nonce = bytes([0x10]) + a2 + (0x0000000000ff).to_bytes(6, "big")
aad = struct.pack("<H", fc & ~0x3800) + a1 + a2 + a3 + struct.pack("<H", 0x1230 & 0xf)
ct = AESCCM(tk, tag_length=8).encrypt(nonce, body2, aad)
p = (0xff).to_bytes(6, "little")
out += c("pmf_action_enc", hdr + bytes([p[0], p[1], 0, 0x20, p[2], p[3], p[4], p[5]]) + ct)

igtk = bytes(range(100, 116))
bc = bytes([0xff] * 6)
def bip(body, keyid, ipn):
    fc = 0x00c0
    hdr = struct.pack("<H", fc) + b"\x00\x00" + bc + a2 + a3 + struct.pack("<H", 0x2340)
    mme0 = bytes([76, 16]) + struct.pack("<H", keyid) + ipn.to_bytes(6, "little")
    aad = struct.pack("<H", fc) + bc + a2 + a3
    m = CMAC(algorithms.AES(igtk)); m.update(aad + body + mme0 + bytes(8))
    return hdr + body + mme0 + m.finalize()[:8]
out += c("pmf_igtk", igtk) + c("pmf_bip", bip(struct.pack("<H", 2), 4, 0x0000000a0b0c))
open("Tools/pmf_vectors.h", "w").write(out)
